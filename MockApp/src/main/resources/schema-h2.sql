CREATE TABLE IF NOT EXISTS WAREHOUSE (
    W_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    W_NAME VARCHAR(10) NOT NULL,
    W_STREET_1 VARCHAR(20) NOT NULL,
    W_STREET_2 VARCHAR(20) NOT NULL,
    W_CITY VARCHAR(20) NOT NULL,
    W_STATE VARCHAR(2) NOT NULL,
    W_ZIP VARCHAR(9) NOT NULL,
    W_TAX NUMERIC(4,4) NOT NULL,
    W_YTD NUMERIC(12,2) NOT NULL
);

CREATE TABLE IF NOT EXISTS DISTRICT (
    D_W_ID BIGINT NOT NULL,
    D_ID BIGINT NOT NULL,
    D_NAME VARCHAR(10) NOT NULL,
    D_STREET_1 VARCHAR(20) NOT NULL,
    D_STREET_2 VARCHAR(20) NOT NULL,
    D_CITY VARCHAR(20) NOT NULL,
    D_STATE VARCHAR(2) NOT NULL,
    D_ZIP VARCHAR(9) NOT NULL,
    D_TAX NUMERIC(4,4) NOT NULL,
    D_YTD NUMERIC(12,2) NOT NULL,
    D_NEXT_O_ID BIGINT NOT NULL,
    PRIMARY KEY (D_W_ID, D_ID),
    CONSTRAINT FK_DISTRICT_WAREHOUSE FOREIGN KEY (D_W_ID) REFERENCES WAREHOUSE(W_ID)
);

CREATE INDEX IF NOT EXISTS IDX_D_W_ID ON DISTRICT(D_W_ID);
CREATE INDEX IF NOT EXISTS IDX_D_W_ID_D_ID ON DISTRICT(D_W_ID, D_ID);

CREATE TABLE IF NOT EXISTS CUSTOMER (
    C_W_ID BIGINT NOT NULL,
    C_D_ID BIGINT NOT NULL,
    C_ID BIGINT NOT NULL,
    C_FIRST VARCHAR(16) NOT NULL,
    C_MIDDLE VARCHAR(2) NOT NULL,
    C_LAST VARCHAR(16) NOT NULL,
    C_STREET_1 VARCHAR(20) NOT NULL,
    C_STREET_2 VARCHAR(20) NOT NULL,
    C_CITY VARCHAR(20) NOT NULL,
    C_STATE VARCHAR(2) NOT NULL,
    C_ZIP VARCHAR(9) NOT NULL,
    C_PHONE VARCHAR(16) NOT NULL,
    C_SINCE TIMESTAMP NOT NULL,
    C_CREDIT VARCHAR(2) NOT NULL,
    C_CREDIT_LIM NUMERIC(12,2) NOT NULL,
    C_DISCOUNT NUMERIC(4,4) NOT NULL,
    C_BALANCE NUMERIC(12,2) NOT NULL,
    C_YTD_PAYMENT NUMERIC(12,2) NOT NULL,
    C_PAYMENT_CNT INTEGER NOT NULL,
    C_DELIVERY_CNT INTEGER NOT NULL,
    C_DATA VARCHAR(500) NOT NULL,
    PRIMARY KEY (C_W_ID, C_D_ID, C_ID),
    CONSTRAINT FK_CUSTOMER_DISTRICT FOREIGN KEY (C_W_ID, C_D_ID) REFERENCES DISTRICT(D_W_ID, D_ID)
);

CREATE INDEX IF NOT EXISTS IDX_C_W_ID_C_D_ID ON CUSTOMER(C_W_ID, C_D_ID);
CREATE INDEX IF NOT EXISTS IDX_C_W_ID_C_D_ID_C_LAST ON CUSTOMER(C_W_ID, C_D_ID, C_LAST, C_FIRST);

CREATE TABLE IF NOT EXISTS ITEM (
    I_ID BIGINT PRIMARY KEY,
    I_IM_ID BIGINT,
    I_NAME VARCHAR(24) NOT NULL,
    I_PRICE NUMERIC(5,2) NOT NULL,
    I_DATA VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS HISTORY (
    H_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    H_C_ID BIGINT NOT NULL,
    H_C_D_ID BIGINT NOT NULL,
    H_C_W_ID BIGINT NOT NULL,
    H_D_ID BIGINT NOT NULL,
    H_W_ID BIGINT NOT NULL,
    H_DATE TIMESTAMP NOT NULL,
    H_AMOUNT NUMERIC(6,2) NOT NULL,
    H_DATA VARCHAR(24) NOT NULL,
    CONSTRAINT FK_HISTORY_CUSTOMER FOREIGN KEY (H_C_W_ID, H_C_D_ID, H_C_ID)
        REFERENCES CUSTOMER(C_W_ID, C_D_ID, C_ID),
    CONSTRAINT FK_HISTORY_DISTRICT FOREIGN KEY (H_W_ID, H_D_ID)
        REFERENCES DISTRICT(D_W_ID, D_ID)
);

CREATE INDEX IF NOT EXISTS IDX_H_C_W_C_D_C_ID ON HISTORY(H_C_W_ID, H_C_D_ID, H_C_ID);
CREATE INDEX IF NOT EXISTS IDX_H_W_D ON HISTORY(H_W_ID, H_D_ID);

CREATE TABLE IF NOT EXISTS STOCK (
    S_W_ID BIGINT NOT NULL,
    S_I_ID BIGINT NOT NULL,
    S_QUANTITY INTEGER NOT NULL,
    S_DIST_01 VARCHAR(24) NOT NULL,
    S_DIST_02 VARCHAR(24) NOT NULL,
    S_DIST_03 VARCHAR(24) NOT NULL,
    S_DIST_04 VARCHAR(24) NOT NULL,
    S_DIST_05 VARCHAR(24) NOT NULL,
    S_DIST_06 VARCHAR(24) NOT NULL,
    S_DIST_07 VARCHAR(24) NOT NULL,
    S_DIST_08 VARCHAR(24) NOT NULL,
    S_DIST_09 VARCHAR(24) NOT NULL,
    S_DIST_10 VARCHAR(24) NOT NULL,
    S_YTD INTEGER NOT NULL,
    S_ORDER_CNT INTEGER NOT NULL,
    S_REMOTE_CNT INTEGER NOT NULL,
    S_DATA VARCHAR(50) NOT NULL,
    PRIMARY KEY (S_W_ID, S_I_ID),
    CONSTRAINT FK_STOCK_WAREHOUSE FOREIGN KEY (S_W_ID) REFERENCES WAREHOUSE(W_ID),
    CONSTRAINT FK_STOCK_ITEM FOREIGN KEY (S_I_ID) REFERENCES ITEM(I_ID)
);

CREATE INDEX IF NOT EXISTS IDX_S_I_ID ON STOCK(S_I_ID);

CREATE TABLE IF NOT EXISTS ORDERS (
    O_W_ID BIGINT NOT NULL,
    O_D_ID BIGINT NOT NULL,
    O_ID BIGINT NOT NULL,
    O_C_ID BIGINT NOT NULL,
    O_ENTRY_D TIMESTAMP NOT NULL,
    O_CARRIER_ID BIGINT,
    O_OL_CNT INTEGER NOT NULL,
    O_ALL_LOCAL INTEGER NOT NULL,
    PRIMARY KEY (O_W_ID, O_D_ID, O_ID),
    CONSTRAINT FK_ORDERS_DISTRICT FOREIGN KEY (O_W_ID, O_D_ID) REFERENCES DISTRICT(D_W_ID, D_ID),
    CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (O_W_ID, O_D_ID, O_C_ID) REFERENCES CUSTOMER(C_W_ID, C_D_ID, C_ID)
);

CREATE INDEX IF NOT EXISTS IDX_O_W_ID_O_D_ID_O_C_ID_O_ID ON ORDERS(O_W_ID, O_D_ID, O_C_ID, O_ID);
CREATE INDEX IF NOT EXISTS IDX_O_W_ID_O_D_ID_O_ID ON ORDERS(O_W_ID, O_D_ID, O_ID);

CREATE TABLE IF NOT EXISTS NEW_ORDER (
    NO_W_ID BIGINT NOT NULL,
    NO_D_ID BIGINT NOT NULL,
    NO_O_ID BIGINT NOT NULL,
    PRIMARY KEY (NO_W_ID, NO_D_ID, NO_O_ID),
    CONSTRAINT FK_NEW_ORDER_ORDERS FOREIGN KEY (NO_W_ID, NO_D_ID, NO_O_ID)
        REFERENCES ORDERS(O_W_ID, O_D_ID, O_ID)
);

CREATE TABLE IF NOT EXISTS ORDER_LINE (
    OL_W_ID BIGINT NOT NULL,
    OL_D_ID BIGINT NOT NULL,
    OL_O_ID BIGINT NOT NULL,
    OL_NUMBER INTEGER NOT NULL,
    OL_I_ID BIGINT NOT NULL,
    OL_SUPPLY_W_ID BIGINT NOT NULL,
    OL_DELIVERY_D TIMESTAMP,
    OL_QUANTITY INTEGER NOT NULL,
    OL_AMOUNT NUMERIC(6,2) NOT NULL,
    OL_DIST_INFO VARCHAR(24) NOT NULL,
    PRIMARY KEY (OL_W_ID, OL_D_ID, OL_O_ID, OL_NUMBER),
    CONSTRAINT FK_ORDER_LINE_ORDER FOREIGN KEY (OL_W_ID, OL_D_ID, OL_O_ID)
        REFERENCES ORDERS(O_W_ID, O_D_ID, O_ID),
    CONSTRAINT FK_ORDER_LINE_ITEM FOREIGN KEY (OL_I_ID)
        REFERENCES ITEM(I_ID),
    CONSTRAINT FK_ORDER_LINE_SUPPLY_WAREHOUSE FOREIGN KEY (OL_SUPPLY_W_ID)
        REFERENCES WAREHOUSE(W_ID)
);
